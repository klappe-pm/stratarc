#!/usr/bin/env python3
"""Generate the two reference pages that come from the code, and keep them from drifting.

The command reference comes from the argparse tree of `stratarc.cli`, and the error catalog from `stratarc.messages`. They are committed under docs/reference/generated/.

    generate-reference.py                    rewrite the committed generated pages
    generate-reference.py --check            exit 6 when a committed generated page differs

This is a development tool. It is not part of the installed package.

Exit statuses: 0 ok, 2 invalid input, 6 a committed generated page differs from the code.
"""

from __future__ import annotations

import argparse
import importlib
import re
import sys
from pathlib import Path

ENGINE_ROOT = Path(__file__).resolve().parents[2]
if str(ENGINE_ROOT) not in sys.path:
    sys.path.insert(0, str(ENGINE_ROOT))
sys.dont_write_bytecode = True
GENERATED_DIR = "docs/reference/generated"
REPO_URL = "https://github.com/klappe-pm/stratarc"
GENERATED_NOTE = "<!-- generated by scripts/docs/generate-reference.py from the code; do not edit by hand -->"

EXIT_STATUS_ROWS = (
    (0, "ok"),
    (1, "failure: the command ran and did not succeed"),
    (2, "invalid input: a bad argument, an unknown source root, an invalid `stratarc.toml`, or a refusal by the engine"),
    (3, "denied: the home is missing or not writable"),
    (4, "conflict: the target already holds something"),
    (5, "unavailable: a packaged resource is missing, a file in the home is newer than this stratarc, an adapter does not support the installed runtime, or the change log database is locked"),
    (6, "drift: the deployed files differ from what the source renders"),
    (130, "interrupted"),
)

# Resource parsers that live in the modules that own them: (command, module, factory). A parser that cannot be loaded is listed by its summary line only.
RESOURCE_PARSERS = (
    ("adapter", "stratarc.registry", "_parser"),
)


# ----- generated pages -----


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def _cell(text: str) -> str:
    return text.replace("|", "&#124;").replace("\n", " ")


def _sentence(text: str | None) -> str:
    """The help text as a sentence that ends in a full stop, or an empty string."""
    text = (text or "").strip()
    if not text:
        return ""
    text = text.replace("; repeatable", ". Repeatable")
    return text[0].upper() + text[1:] if text.endswith(".") else text[0].upper() + text[1:] + "."


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return lines


def _subparsers_action(parser: argparse.ArgumentParser) -> argparse._SubParsersAction | None:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return action
    return None


def _children(parser: argparse.ArgumentParser) -> list[tuple[str, str, argparse.ArgumentParser]]:
    """The (name, help, parser) of each subcommand, in the order they were registered."""
    action = _subparsers_action(parser)
    if action is None:
        return []
    helps = {choice.dest: (choice.help or "") for choice in action._choices_actions}
    return [(name, helps.get(name, ""), sub) for name, sub in action.choices.items()]


def _option_label(action: argparse.Action) -> str:
    flags = ", ".join(f"`{s}`" for s in action.option_strings)
    if action.nargs == 0:
        return flags
    metavar = action.metavar or action.dest.upper()
    return f"{flags} `{metavar}`"


def _own_options(parser: argparse.ArgumentParser, skip: set[str]) -> list[argparse.Action]:
    out = []
    for action in parser._actions:
        if isinstance(action, (argparse._HelpAction, argparse._VersionAction, argparse._SubParsersAction)):
            continue
        if not action.option_strings or action.help == argparse.SUPPRESS:
            continue
        if set(action.option_strings) & skip:
            continue
        out.append(action)
    return out


def _positionals(parser: argparse.ArgumentParser) -> list[argparse.Action]:
    return [a for a in parser._actions if not a.option_strings and not isinstance(a, argparse._SubParsersAction)]


def _usage(path: str, parser: argparse.ArgumentParser, skip: set[str]) -> str:
    parts = [path]
    kids = _children(parser)
    if kids:
        parts.append("{" + ",".join(name for name, _, _ in kids) + "}")
    for action in _positionals(parser):
        name = action.metavar or action.dest
        if action.choices and not action.metavar:
            name = "{" + ",".join(str(c) for c in action.choices) + "}"
        optional = action.nargs in ("?", "*")
        parts.append(f"[{name}]" if optional else name)
    for action in _own_options(parser, skip):
        flag = action.option_strings[0]
        text = flag if action.nargs == 0 else f"{flag} {action.metavar or action.dest.upper()}"
        parts.append(text if action.required else f"[{text}]")
    return " ".join(parts)


def _arguments_block(parser: argparse.ArgumentParser, skip: set[str]) -> list[str]:
    lines: list[str] = []
    positionals = _positionals(parser)
    if positionals:
        rows = []
        for action in positionals:
            name = action.metavar or action.dest
            detail = _sentence(action.help)
            if action.choices:
                detail = (detail + " " if detail else "") + "One of " + ", ".join(f"`{c}`" for c in action.choices) + "."
            rows.append([f"`{name}`", detail])
        lines += ["", *_table(["argument", "meaning"], rows)]
    options = _own_options(parser, skip)
    if options:
        rows = []
        for a in options:
            detail = _sentence(a.help)
            if isinstance(a, argparse._AppendAction) and "repeatable" not in detail.lower():
                detail = (detail + " " if detail else "") + "Repeatable."
            rows.append([_option_label(a), detail])
        lines += ["", *_table(["option", "meaning"], rows)]
    return lines


def _load_resource_parser(module: str, factory: str) -> argparse.ArgumentParser | None:
    try:
        parser = getattr(importlib.import_module(module), factory)()
    except Exception:  # a renamed or broken factory leaves the summary line in place
        return None
    return parser if isinstance(parser, argparse.ArgumentParser) else None


def _module_help(name: str) -> str | None:
    """The --help text of a command whose module owns its parser, or None when it cannot be read."""
    import contextlib
    import io

    from stratarc import cli

    captured = io.StringIO()
    try:
        with contextlib.redirect_stdout(captured), contextlib.redirect_stderr(io.StringIO()):
            try:
                cli._engine_main(name)(["--help"])
            except SystemExit:
                pass
    except Exception:
        return None
    text = captured.getvalue().strip("\n")
    if not text:
        return None
    # Keep the usage block and the option list; the module's description is prose that belongs in a page of its own.
    blocks = text.split("\n\n")
    usage = blocks[0]
    rest = text[text.index("options:"):] if "options:" in text else ""
    return "\n\n".join(part for part in (usage, rest) if part)


def _command_section(name: str, summary: str, parser: argparse.ArgumentParser | None, global_flags: set[str]) -> list[str]:
    lines = ["", f"## `{name}`", ""]
    if parser is None:
        lines.append(summary + ".")
        text = _module_help(name)
        if text:
            lines += ["", "```text", text.replace("prog ", "stratarc "), "```"]
        else:
            lines += ["", f"This command forwards its arguments to its own parser. Run `stratarc {name} --help` for them."]
        return lines
    lines.append((summary or (parser.description or "")).rstrip(".") + ".")
    lines += ["", "```text", _usage(f"stratarc {name}", parser, global_flags), "```"]
    lines += _arguments_block(parser, global_flags)
    for child, child_help, child_parser in _children(parser):
        inherited = global_flags | {s for a in _own_options(parser, set()) for s in a.option_strings}
        lines += ["", f"### `{name} {child}`", "", (child_help or "").rstrip(".") + ".", "", "```text", _usage(f"stratarc {name} {child}", child_parser, inherited), "```"]
        lines += _arguments_block(child_parser, inherited)
    return lines


def generate_commands_page() -> str:
    from stratarc import cli

    parser = cli.build_parser()
    global_group = next(g for g in parser._action_groups if g.title == "global options")
    global_actions = [a for a in global_group._group_actions]
    global_flags = {s for a in global_actions for s in a.option_strings}
    resources = {name: _load_resource_parser(module, factory) for name, module, factory in RESOURCE_PARSERS}

    summary_rows = []
    sections: list[str] = []
    for name, help_text, sub in _children(parser):
        summary_rows.append([f"[`{name}`](#{slug(name)})", help_text])
        has_own = any(not isinstance(a, argparse._HelpAction) for a in sub._actions) or _children(sub)
        chosen = sub if has_own else resources.get(name)
        sections += _command_section(name, help_text, chosen, global_flags)

    lines = [
        "# Commands",
        "",
        GENERATED_NOTE,
        "",
        "Every command of `stratarc`, generated from the command line parser so the page cannot drift from the code. Run `python3 scripts/docs/generate-reference.py --check` to confirm it still matches.",
        "",
        "## Global Options",
        "",
        "Global options are accepted before or after the command.",
        "",
        *_table(["option", "meaning"], [[_option_label(a), a.help or ""] for a in global_actions]),
        "",
        "## Exit Statuses",
        "",
        *_table(["status", "meaning"], [[str(code), text] for code, text in EXIT_STATUS_ROWS]),
        "",
        "## Command List",
        "",
        *_table(["command", "summary"], summary_rows),
        *sections,
    ]
    return "\n".join(lines) + "\n"


def generate_errors_page() -> str:
    from stratarc import messages

    status_names = {
        messages.FAILURE: "failure",
        messages.INVALID_INPUT: "invalid-input",
        messages.DENIED: "denied",
        messages.CONFLICT: "conflict",
        messages.UNAVAILABLE: "unavailable",
        messages.DRIFT: "drift",
        messages.INTERRUPTED: "interrupted",
    }
    codes_by_id: dict[str, list[str]] = {}
    for code, message_id in messages.CODE_MESSAGES.items():
        codes_by_id.setdefault(message_id, []).append(code)

    catalog = sorted(messages.CATALOG.values(), key=lambda m: m.id)
    lines = [
        "# Errors",
        "",
        GENERATED_NOTE,
        "",
        "Every message the command line can print, generated from `stratarc/messages.py`. Each message has an id, and the command line links to the entry with the same id on this page. A placeholder in braces, such as `{path}`, is filled in by the command.",
        "",
        "## Message List",
        "",
        *_table(
            ["id", "status", "problem"],
            [[f"[`{m.id}`](#{m.id})", f"{m.exit} {status_names.get(m.exit, '')}".strip(), m.problem] for m in catalog],
        ),
        "",
        "## Messages",
    ]
    for m in catalog:
        lines += [
            "",
            f"### `{m.id}`",
            "",
            f"Ends the command with status {m.exit} ({status_names.get(m.exit, 'ok')}).",
            "",
            f"Problem: {m.problem}",
            "",
            f"Recovery: {m.recovery}",
        ]
        codes = codes_by_id.get(m.id)
        if codes:
            lines += ["", "Raised for the module " + ("code " if len(codes) == 1 else "codes ") + ", ".join(f"`{c}`" for c in sorted(codes)) + "."]
    return "\n".join(lines) + "\n"


def generated_pages() -> dict[str, str]:
    """The generated pages by repository-relative path."""
    return {
        f"{GENERATED_DIR}/commands.md": generate_commands_page(),
        f"{GENERATED_DIR}/errors.md": generate_errors_page(),
    }


def write_generated(repo: Path) -> list[str]:
    written = []
    for rel, text in generated_pages().items():
        target = repo / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            target.write_text(text, encoding="utf-8")
            written.append(rel)
    return written


def check_generated(repo: Path) -> list[str]:
    """The generated pages whose committed copy is missing or differs from the code."""
    stale = []
    for rel, text in generated_pages().items():
        target = repo / rel
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            stale.append(rel)
    return stale


# ----- command line -----


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="generate-reference.py", description="Rewrite the generated reference pages, or check that they match the code.")
    parser.add_argument("--repo", metavar="PATH", default=str(ENGINE_ROOT), help="the repository whose docs/ is written (default: this repository)")
    parser.add_argument("--check", action="store_true", help="exit 6 when a committed generated page differs from the code; write nothing")
    try:
        args = parser.parse_args(argv)
    except SystemExit as stop:
        return 0 if stop.code in (0, None) else 2
    repo = Path(args.repo).resolve()
    if not repo.is_dir():
        print(f"error: {repo} is not a directory", file=sys.stderr)
        return 2
    sys.path.insert(0, str(ENGINE_ROOT))
    if args.check:
        stale = check_generated(repo)
        for rel in stale:
            print(f"stale: {rel}", file=sys.stderr)
        if stale:
            print("run: python3 scripts/docs/generate-reference.py", file=sys.stderr)
            return 6
        print("generated pages match the code")
        return 0
    for rel in write_generated(repo):
        print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
